"""The only functions the app and the evaluation call. SHARED FILE: see AGENTS.md §4.

With ATLAS_FAKE=1 every function returns data from atlas/fake.py. Core replaces each
NotImplementedError with the real call when it works, and says so in notes/core.md.
The RAG baseline is not here: it belongs to Product (evaluation/rag.py).
"""
from __future__ import annotations

import os
from datetime import date
from pathlib import Path

from dotenv import load_dotenv

from atlas.contracts import Answer, BuildResult, ChangeSet, Chunk, Strategy, ValidationReport

load_dotenv()

ROOT = Path(__file__).resolve().parents[1]


def fake_mode() -> bool:
    return os.getenv("ATLAS_FAKE", "1") == "1"


def corpus() -> list[Chunk]:
    """The corpus, split by its own structure (article, paragraph, annex point)."""
    if fake_mode():
        from atlas import fake
        return fake.corpus()
    from atlas.corpus.chunker import load
    return list(load())


def build_ontology(strategy: Strategy) -> BuildResult:
    """Build the ontology with strategy A (free extraction) or B (guided by the CQs and the structure)."""
    if fake_mode():
        from atlas import fake
        return fake.build_ontology(strategy)
    from atlas.ontology import build
    return build.build_result(strategy)


def ontology_file(strategy: Strategy) -> Path:
    """Where the Turtle file of a strategy lives (generated by Core, committed)."""
    return ROOT / "ontology" / strategy / "ontology.ttl"


def answer(question: str, strategy: Strategy = "B", as_of: date | None = None) -> Answer:
    """Answer through the ontology of a strategy (SPARQL), citing triples and passages."""
    if fake_mode():
        from atlas import fake
        return fake.answer(question, strategy, as_of)
    from atlas.ontology import build
    return build.answer(question, strategy, as_of)


def validate(strategy: Strategy) -> ValidationReport:
    """SHACL validation of the ontology of a strategy."""
    if fake_mode():
        from atlas import fake
        return fake.validate(strategy)
    from atlas.ontology import build
    return build.validation(strategy)


def propose_change(document: Path) -> ChangeSet:
    """A new or changed document: the proposed changes to ontology B, each with its passage."""
    if fake_mode():
        from atlas import fake
        return fake.propose_change(document)
    from atlas.ontology import change
    return change.propose_change(document)


def apply_change(changeset: ChangeSet, accepted: list[str]) -> BuildResult:
    """Apply the accepted changes: a new version of ontology B."""
    if fake_mode():
        from atlas import fake
        return fake.apply_change(changeset, accepted)
    from atlas.ontology import change
    return change.apply_change(changeset, accepted)
